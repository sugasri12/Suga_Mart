/**
 * Find a single product by its unique product ID
 * @param {number|string} id 
 * @returns {object|null}
 */
function getProductById(id) {
    const numId = Number(id);
    return products.find(function(item) {
        return Number(item.id) === numId;
    }) || null;
}

